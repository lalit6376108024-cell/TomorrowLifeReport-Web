import os
from datetime import date, timedelta
from functools import wraps
from flask import Flask, jsonify, render_template, request, session, redirect, url_for
from sqlalchemy import create_engine, text

app = Flask(__name__)
app.secret_key = os.environ.get('SECRET_KEY', 'local-only-change-me')
APP_PASSWORD = os.environ.get('APP_PASSWORD', 'local-only-change-me')
db_url = os.environ.get('DATABASE_URL', '').strip()
if db_url.startswith('postgres://'):
    db_url = db_url.replace('postgres://', 'postgresql+psycopg://', 1)
elif db_url.startswith('postgresql://') and '+psycopg' not in db_url:
    db_url = db_url.replace('postgresql://', 'postgresql+psycopg://', 1)
engine = create_engine(db_url, pool_pre_ping=True) if db_url else create_engine('sqlite:///tomorrowlife.db', connect_args={'check_same_thread': False})

def init_db():
    with engine.begin() as c:
        if db_url:
            c.execute(text('''CREATE TABLE IF NOT EXISTS entries (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                entry_date VARCHAR(10) NOT NULL, category VARCHAR(80) NOT NULL,
                title VARCHAR(160) NOT NULL, planned_minutes INTEGER NOT NULL DEFAULT 0,
                actual_minutes INTEGER NOT NULL DEFAULT 0, notes TEXT NOT NULL DEFAULT '',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)'''))
        else:
            c.execute(text('''CREATE TABLE IF NOT EXISTS entries (
                id INTEGER PRIMARY KEY AUTOINCREMENT, entry_date TEXT NOT NULL,
                category TEXT NOT NULL, title TEXT NOT NULL,
                planned_minutes INTEGER NOT NULL DEFAULT 0, actual_minutes INTEGER NOT NULL DEFAULT 0,
                notes TEXT NOT NULL DEFAULT '', created_at TEXT DEFAULT CURRENT_TIMESTAMP)'''))
init_db()

def protected(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if not session.get('logged_in'):
            if request.path.startswith('/api/'):
                return jsonify(error='Please sign in first.'), 401
            return redirect(url_for('login'))
        return fn(*args, **kwargs)
    return wrapper

@app.get('/login')
def login():
    return render_template('login.html', error='')

@app.post('/login')
def login_post():
    if request.form.get('password', '') == APP_PASSWORD:
        session['logged_in'] = True
        return redirect('/')
    return render_template('login.html', error="Password didn't match. Try again."), 401

@app.post('/logout')
def logout():
    session.clear()
    return redirect('/login')

@app.get('/')
@protected
def index():
    return render_template('index.html', today=date.today().isoformat())

@app.get('/api/health')
def health():
    try:
        with engine.connect() as c: c.execute(text('SELECT 1'))
        return jsonify(status='ok', database='connected')
    except Exception:
        return jsonify(status='error', database='unavailable'), 503

@app.get('/api/entries')
@protected
def get_entries():
    day = request.args.get('date', date.today().isoformat())[:10]
    with engine.connect() as c:
        rows = c.execute(text('''SELECT id,entry_date,category,title,planned_minutes,actual_minutes,notes
            FROM entries WHERE entry_date=:d ORDER BY id DESC'''), {'d': day}).mappings().all()
    return jsonify([dict(r) for r in rows])

@app.post('/api/entries')
@protected
def create_entry():
    data = request.get_json(silent=True) or {}
    title = str(data.get('title', '')).strip()[:160]
    category = str(data.get('category', 'Focus')).strip()[:80] or 'Focus'
    day = str(data.get('entry_date', date.today().isoformat()))[:10]
    notes = str(data.get('notes', '')).strip()[:4000]
    try:
        planned, actual = int(data.get('planned_minutes', 0)), int(data.get('actual_minutes', 0))
        date.fromisoformat(day)
    except (TypeError, ValueError):
        return jsonify(error='Use a valid date and whole-number minutes.'), 400
    if not title: return jsonify(error='Activity title is required.'), 400
    if min(planned, actual) < 0 or max(planned, actual) > 1440:
        return jsonify(error='Minutes must be between 0 and 1440.'), 400
    with engine.begin() as c:
        params = {'d':day,'c':category,'t':title,'p':planned,'a':actual,'n':notes}
        if db_url:
            new_id = c.execute(text('''INSERT INTO entries
                (entry_date,category,title,planned_minutes,actual_minutes,notes)
                VALUES(:d,:c,:t,:p,:a,:n) RETURNING id'''), params).scalar_one()
        else:
            result = c.execute(text('''INSERT INTO entries
                (entry_date,category,title,planned_minutes,actual_minutes,notes)
                VALUES(:d,:c,:t,:p,:a,:n)'''), params)
            new_id = result.lastrowid
    return jsonify(id=new_id, message='Activity saved.'), 201

@app.delete('/api/entries/<int:entry_id>')
@protected
def delete_entry(entry_id):
    with engine.begin() as c:
        result = c.execute(text('DELETE FROM entries WHERE id=:id'), {'id':entry_id})
    return (jsonify(message='Deleted.'), 200) if result.rowcount else (jsonify(error='Not found.'), 404)

@app.get('/api/reports/weekly')
@protected
def weekly_report():
    try: end = date.fromisoformat(request.args.get('end', date.today().isoformat()))
    except ValueError: return jsonify(error='Use YYYY-MM-DD for end date.'), 400
    start = end - timedelta(days=6)
    with engine.connect() as c:
        rows = c.execute(text('''SELECT entry_date,category,planned_minutes,actual_minutes
            FROM entries WHERE entry_date BETWEEN :s AND :e'''), {'s':start.isoformat(),'e':end.isoformat()}).mappings().all()
    planned = sum(int(r['planned_minutes']) for r in rows); actual = sum(int(r['actual_minutes']) for r in rows)
    days, categories = {}, {}
    for r in rows:
        days[r['entry_date']] = days.get(r['entry_date'], 0) + int(r['actual_minutes'])
        categories[r['category']] = categories.get(r['category'], 0) + int(r['actual_minutes'])
    suggestions = []
    if not rows: suggestions.append('Log activities for a few days to find patterns that are useful to you.')
    else:
        if planned and actual < planned * .7: suggestions.append('Try fewer, clearer priorities tomorrow; recorded time was below plan.')
        if planned and actual > planned * 1.15: suggestions.append('Add buffer time tomorrow; recorded time exceeded your plan.')
        if len(days) < 5: suggestions.append(f'You logged activities on {len(days)} of 7 days. A short daily review may help.')
        if categories: suggestions.append('Your largest recorded category was ' + max(categories, key=categories.get) + '. Does that match your priorities?')
        if not suggestions: suggestions.append('Keep the routine sustainable: protect sleep, schedule breaks, and choose 1–3 priorities.')
    daily = [{'date':(start+timedelta(days=i)).isoformat(), 'minutes':days.get((start+timedelta(days=i)).isoformat(),0)} for i in range(7)]
    return jsonify(start_date=start.isoformat(), end_date=end.isoformat(), activity_count=len(rows), planned_minutes=planned, actual_minutes=actual, days_logged=len(days), daily_minutes=daily, suggestions=suggestions)

if __name__ == '__main__': app.run(host='0.0.0.0', port=int(os.environ.get('PORT','5000')), debug=True)
